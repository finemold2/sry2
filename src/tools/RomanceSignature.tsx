const pick = <T,>(a: T[]): T => a[Math.floor(Math.random() * a.length)]

// 천 단위 콤마(한국어 로캘)
const fmt = (n: number) => n.toLocaleString('ko-KR')

// 전체(모든 슬롯) 조합수 — "총 조합" 표기용. 도시에 목표: 1조+ 지향.
const TOTAL_COMBOS = SLOTS.reduce((acc, s) => acc * s.faces.length, 1)

// 큰 수를 한국어 단위(조/억/만)로 읽기 쉽게.
function humanCount(n: number): string {
  if (n >= 1e12) return (n / 1e12).toFixed(n >= 1e13 ? 0 : 1).replace(/\.0$/, '') + '조+'
  if (n >= 1e8) return (n / 1e8).toFixed(n >= 1e9 ? 0 : 1).replace(/\.0$/, '') + '억+'
  if (n >= 1e4) return (n / 1e4).toFixed(0) + '만+'
  return fmt(n)
}

// 활성 슬롯들의 조합 가짓수.
function comboCount(activeKeys: string[]): number {
  return activeKeys.reduce((acc, k) => {
    const s = SLOTS.find((x) => x.key === k)
    return acc * (s ? s.faces.length : 1)
  }, 1)
}

// 굴린 결과들을 "첫 만남 → 점화 → 파국 → 그랜드 제스처 → HEA" 흐름의 관계 전개 단락으로 엮는다.
function compose(by: Record<string, string>): string {
  const meet = by.meet, spark = by.spark, tension = by.tension
  const obstacle = by.obstacle, confess = by.confess, moment = by.moment
  const parts: string[] = []
  if (meet) parts.push(`두 사람은 ${meet}`)
  if (spark) parts.push(`그러던 중 ${spark}에 마음이 흔들리기 시작한다`)
  if (tension) parts.push(`${tension}, 가까워졌다 멀어지기를 반복한다`)
  if (obstacle) parts.push(`그러나 ${obstacle}. 관계는 끝장난 듯 최저점으로 떨어진다`)
  if (confess) parts.push(`절망 끝에 그(녀)는 ${confess}`)
  if (moment) parts.push(`마침내 ${moment}`)
  if (!parts.length) return ''
  return parts.map((p) => p.replace(/[.。]$/, '')).join('. ') + '.'
}

// HTML 이스케이프 — 프로젝트 본문(HTML) 주입 안전화.
function escHtml(s: string): string {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

