const fmtCombo = (n: number) => {
  // 천 단위 구분 — 일반 문자만(쉼표) 사용
  const s = String(n)
  let out = ''
  for (let i = 0; i < s.length; i++) {
    if (i > 0 && (s.length - i) % 3 === 0) out += ','
    out += s[i]
  }
  return out
}

