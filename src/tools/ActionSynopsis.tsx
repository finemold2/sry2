// 톤에 맞는 슬롯 풀을 돌려준다.
function poolFor(slot: SlotDef, tone: string): string[] {
  if (slot.pool) return slot.pool
  if (slot.byTone) return slot.byTone[tone] || slot.byTone[TONES[0].key]
  return []
}

// 총 조합수(현재 톤 기준 슬롯 풀 크기의 곱) — 1조+ 지향
function totalCombos(tone: string): number {
  return SLOTS.reduce((n, s) => n * Math.max(1, poolFor(s, tone).length), 1)
}

// 한 편의 시놉시스 문장으로 종합.
function compose(title: string, logline: string, tone: string, r: Record<string, string>): string {
  const t = TONES.find((x) => x.key === tone)
  const toneLabel = t ? t.label : ''
  const lines: string[] = []
  const T = title.trim() || '(제목 미정)'
  lines.push(`《${T}》 — ${toneLabel} · 액션·전쟁`)
  if (logline.trim()) lines.push(`한 줄 로그라인: ${logline.trim()}`)
  lines.push('')

  // [발단] 콜드오픈 + 주인공 + 이해관계
  if (r.cold || r.hero) {
    const cold = r.cold ? `${r.cold} 이야기는 문을 연다. ` : ''
    const hero = r.hero ? `주인공은 ${r.hero}.` : ''
    lines.push(`■ 발단 — ${cold}${hero}`.trim())
  }
  if (r.stake) lines.push(`걸린 것: ${r.stake}.`)

  // [전개] 시계장치 + 무대 + 능력격차 + 시그니처
  const mid: string[] = []
  if (r.arena) mid.push(`무대는 ${r.arena}`)
  if (r.clock) mid.push(r.clock.replace(/\s*속에서$/, ''))
  if (r.gap) mid.push(r.gap)
  if (r.sign) mid.push(`그의 무기는 ${r.sign}`)
  if (mid.length) lines.push(`■ 전개 — ${mid.join('. ')}.`.replace(/\.\./g, '.').trim())

  // [복선] 체호프 장치
  if (r.chekhov) lines.push(`■ 복선 — ${r.chekhov.replace(/[,，]\s*$/, '')}.`.replace(/\.\./g, '.'))

  // [위기] 중간 패배
  if (r.low) lines.push(`■ 위기(최저점) — ${r.low.replace(/[,，]?\s*$/, '')}, 주인공은 가장 약한 자리에서 다시 일어서야 한다.`.replace(/\.\./g, '.'))

  // [절정] 클라이맥스
  if (r.climax) lines.push(`■ 절정 — ${r.climax}.`.replace(/\.\./g, '.'))

  // [대가] + [여파]
  if (r.cost) lines.push(`승리의 대가: ${r.cost}.`)
  if (r.after) lines.push(`■ 여파 — ${r.after}.`.replace(/\.\./g, '.'))

  return lines.filter((l) => l !== undefined).join('\n').replace(/\n{3,}/g, '\n\n').trim()
}

// 안전한 상태 로드
function loadStr(key: string, fallback: string): string {
  try { const v = localStorage.getItem(LS + ':' + key); return v == null ? fallback : v } catch { return fallback }
}
function loadObj<T>(key: string, fallback: T): T {
  try { const v = localStorage.getItem(LS + ':' + key); if (v) { const o = JSON.parse(v); if (o && typeof o === 'object') return o as T } } catch { /* noop */ }
  return fallback
}

