// 천 단위 구분 표기(조합수)
function fmtNum(n: number): string {
  try { return n.toLocaleString('ko-KR') } catch { return String(n) }
}
// 큰 수 한국어 단위(억/조/경) 보조 표기
function koUnit(n: number): string {
  if (n >= 1e16) return `약 ${(n / 1e16).toFixed(n >= 1e17 ? 0 : 1)}경`
  if (n >= 1e12) return `약 ${(n / 1e12).toFixed(n >= 1e13 ? 0 : 1)}조`
  if (n >= 1e8) return `약 ${(n / 1e8).toFixed(n >= 1e9 ? 0 : 1)}억`
  if (n >= 1e4) return `약 ${(n / 1e4).toFixed(0)}만`
  return fmtNum(n)
}

// 마지막 글자의 받침 유무로 조사 하나만 고른다(을/를·이/가·은/는·으로/로).
//  - 한글이면 유니코드 종성으로 판정. ㄹ 받침은 '으로/로'에서 '로'로 처리(예: 골격으로, 서울로).
//  - 끝이 숫자/영문이면 한글 독음 기준 받침 유무로 판정(영문 자음 끝/대표 숫자=받침 있음 취급).
function lastHasBatchim(word: string): { has: boolean; rieul: boolean } {
  const w = (word || '').trim()
  if (!w) return { has: false, rieul: false }
  const ch = w[w.length - 1]
  const code = ch.charCodeAt(0)
  if (code >= 0xac00 && code <= 0xd7a3) {
    const jong = (code - 0xac00) % 28
    return { has: jong !== 0, rieul: jong === 8 }
  }
  // 숫자: 한글 독음 기준(0영,1일,3삼,6육,7칠,8팔,0공 등 받침 있음 / 2이,4사,5오,9구 받침 없음)
  if (/[0-9]$/.test(w)) {
    const last = w[w.length - 1]
    const batchimDigits = new Set(['0', '1', '3', '6', '7', '8'])
    const rieulDigits = new Set(['1', '7', '8', '0']) // 일/칠/팔/영 → ㄹ
    return { has: batchimDigits.has(last), rieul: rieulDigits.has(last) }
  }
  // 영문: 모음으로 끝나면 받침 없음 취급, 자음으로 끝나면 받침 있음 취급(독음 근사)
  if (/[a-zA-Z]$/.test(w)) {
    const vowel = /[aeiouAEIOU]$/.test(w)
    const rieul = /[lL]$/.test(w)
    return { has: !vowel, rieul }
  }
  return { has: false, rieul: false }
}
// 목적격 을/를 (현재 안내문에서 사용)
function eulReul(word: string): string { return lastHasBatchim(word).has ? '을' : '를' }

function randIdx(len: number): number {
  try {
    if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
      const a = new Uint32Array(1)
      crypto.getRandomValues(a)
      return a[0] % len
    }
  } catch {}
  return Math.floor(Math.random() * len)
}

// 풀 안에서 인덱스 하나를 뽑되, 이미 쓰인 값(used)과 같은 문자열이면 재추첨(최대 풀 크기-1회).
//  - 각 슬롯은 고유 풀(16개 고유 항목)이라 본래 충돌이 드물지만, 슬롯 간 문자열 중복(같은 값 2회 노출)을
//    런타임에서도 확실히 막기 위한 안전장치. 모든 후보가 used에 있으면(이론상) 첫 추첨값을 반환해 슬롯이 비지 않게 한다.
function pickDistinctIdx(pool: string[], used: Set<string>): number {
  if (pool.length === 0) return 0
  let idx = randIdx(pool.length)
  for (let tries = 0; tries < pool.length && used.has(pool[idx]); tries++) {
    idx = randIdx(pool.length)
  }
  // 무작위로도 못 피했으면 순차 탐색으로 안 쓰인 값을 찾는다(결정론적 보장).
  if (used.has(pool[idx])) {
    for (let i = 0; i < pool.length; i++) {
      if (!used.has(pool[i])) { idx = i; break }
    }
  }
  return idx
}

// HTML 이스케이프(프로젝트 bodyHtml 용)
function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

type Answers = Record<string, string>           // `${section}.${field}` → 값
type SkeletonState = Record<string, number>     // slot.key → 선택 인덱스
type LockState = Record<string, boolean>        // slot.key → 잠금

interface Store {
  answers: Answers
  skeleton: SkeletonState
  locks: LockState
  activeSection: string
}

function defaultSkeleton(): SkeletonState {
  const s: SkeletonState = {}
  const used = new Set<string>()
  for (const slot of SLOTS) {
    const idx = pickDistinctIdx(slot.pool, used)
    s[slot.key] = idx
    used.add(slot.pool[idx])
  }
  return s
}

function load(): Store {
  const base: Store = { answers: {}, skeleton: {}, locks: {}, activeSection: SECTIONS[0].key }
  try {
    const raw = localStorage.getItem(LS_KEY)
    if (!raw) return { ...base, skeleton: defaultSkeleton() }
    const p = JSON.parse(raw)
    const answers: Answers = {}
    if (p && p.answers && typeof p.answers === 'object') {
      for (const k of Object.keys(p.answers)) if (typeof p.answers[k] === 'string') answers[k] = p.answers[k]
    }
    // 저장된 인덱스를 복원하되, 누락/손상된 슬롯은 이미 채워진 값과 중복되지 않게 채워 14개 슬롯을 모두 보장.
    const skeleton: SkeletonState = {}
    const used = new Set<string>()
    const missing: typeof SLOTS = []
    for (const slot of SLOTS) {
      const v = p?.skeleton?.[slot.key]
      if (typeof v === 'number' && v >= 0 && v < slot.pool.length) {
        skeleton[slot.key] = v
        used.add(slot.pool[v])
      } else {
        missing.push(slot)
      }
    }
    for (const slot of missing) {
      const idx = pickDistinctIdx(slot.pool, used)
      skeleton[slot.key] = idx
      used.add(slot.pool[idx])
    }
    const locks: LockState = {}
    for (const slot of SLOTS) locks[slot.key] = !!p?.locks?.[slot.key]
    const activeSection = SECTIONS.some((s) => s.key === p?.activeSection) ? p.activeSection : SECTIONS[0].key
    return { answers, skeleton, locks, activeSection }
  } catch {
    return { ...base, skeleton: defaultSkeleton() }
  }
}

