export function randomPrompt(catKey?: string): { text: string; cat: string } {
  const pool = catKey ? PROMPT_CATEGORIES.filter((c) => c.key === catKey) : PROMPT_CATEGORIES
  const cat = pool[Math.floor(Math.random() * pool.length)]
  const text = cat.items[Math.floor(Math.random() * cat.items.length)]
  return { text, cat: cat.label }
}
